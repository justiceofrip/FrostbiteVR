"""Generate DxgiProxyExports.generated.h from the real System32 dxgi.dll export table.

  python tools/release/gen_proxy_exports.py C:\\Windows\\System32\\dxgi.dll > src/platform/windows/bf4/DxgiProxyExports.generated.h

Named exports become GLOBALROOT forwarders; ordinal-only exports are forwarded by ordinal
with NONAME so the proxy's export table matches the original exactly.
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path


def rva_to_off(sections, rva):
    for va, vsize, raw, rsize in sections:
        if va <= rva < va + max(vsize, rsize):
            return rva - va + raw
    raise ValueError(f"rva {rva:#x} not in any section")


def exports(path: Path):
    b = path.read_bytes()
    pe = struct.unpack_from("<I", b, 0x3C)[0]
    nsec = struct.unpack_from("<H", b, pe + 6)[0]
    opt_size = struct.unpack_from("<H", b, pe + 20)[0]
    opt = pe + 24
    magic = struct.unpack_from("<H", b, opt)[0]
    dd = opt + (112 if magic == 0x20B else 96)
    exp_rva, _ = struct.unpack_from("<II", b, dd)
    sections = []
    for i in range(nsec):
        s = opt + opt_size + i * 40
        vsize, va, rsize, raw = struct.unpack_from("<IIII", b, s + 8)
        sections.append((va, vsize, raw, rsize))
    e = rva_to_off(sections, exp_rva)
    base, nfun, nnames, afun, anames, aords = struct.unpack_from("<IIIIII", b, e + 16)
    names = {}
    for i in range(nnames):
        nrva = struct.unpack_from("<I", b, rva_to_off(sections, anames) + 4 * i)[0]
        ordi = struct.unpack_from("<H", b, rva_to_off(sections, aords) + 2 * i)[0]
        no = rva_to_off(sections, nrva)
        names[ordi] = b[no:b.index(b"\0", no)].decode("ascii")
    for i in range(nfun):
        if struct.unpack_from("<I", b, rva_to_off(sections, afun) + 4 * i)[0] == 0:
            continue
        yield base + i, names.get(i)


# Implemented in DxgiProxy.cpp (synchronous FrostbiteVR init on first factory call).
OWNED = {"CreateDXGIFactory", "CreateDXGIFactory1", "CreateDXGIFactory2"}


def main() -> int:
    dll = Path(sys.argv[1] if len(sys.argv) > 1 else r"C:\Windows\System32\dxgi.dll")
    stem = dll.stem
    print(f"// GENERATED by tools/release/gen_proxy_exports.py from {dll}. Do not edit.")
    print("#pragma once")
    print("// Owned (not forwarded): " + ", ".join(sorted(OWNED)) + " - see DxgiProxy.cpp.")
    print(f'#define FVR_DXGI_FWD "\\\\\\\\.\\\\GLOBALROOT\\\\SystemRoot\\\\System32\\\\{stem}.dll."')
    for ordinal, name in exports(dll):
        if name in OWNED:
            continue
        if name:
            print(f'#pragma comment(linker, "/export:{name}=" FVR_DXGI_FWD "{name},@{ordinal}")')
        else:
            print(f'#pragma comment(linker, "/export:__fvr_ord{ordinal}=" FVR_DXGI_FWD "#{ordinal},@{ordinal},NONAME")')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
