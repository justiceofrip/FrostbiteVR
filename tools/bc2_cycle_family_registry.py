"""Generate exact cycle selectors from the reviewed shared native dispatch.

This source review grants only exact native configuration admission. It does
not assert an asset is loaded, physical geometry is reviewed, or live success.
No gun name, metadata class, or nonzero boltTime is an admission predicate.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import struct
from pathlib import Path


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def file_digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def word(value):
    return struct.unpack("<I", struct.pack("<f", value))[0]


def generate(root):
    sniper_path = root / "handoff/tasks/WEAPONS/20261030-sniper43/descriptor-jobs.json"
    proof_path = root / "handoff/tasks/WEAPONS/20261030-sniper43/static-proof.json"
    pump_path = root / "handoff/tasks/WEAPONS/20261030-shotgun43/batch.json"
    sniper = json.loads(sniper_path.read_text(encoding="utf-8"))
    proof = json.loads(proof_path.read_text(encoding="utf-8"))
    pump = json.loads(pump_path.read_text(encoding="utf-8"))
    # Pin the independently inspected source evidence, not merely its labels.
    if file_digest(sniper_path) != "b8dd29acf8e9d0c28b18dc8c1e29b1bfa7b6c16e7c43b62e6b38115995e6f032":
        raise ValueError("Exact sniper source descriptors changed; repeat configuration review")
    if file_digest(proof_path) != "e2bd8d39a8f94dbf342885184c20249458bc14612d9506a4c2f46f7ee07faeca" or file_digest(pump_path) != "1d063afd2be147d8531d6a1a4210971a777e4d3d72715b3cef92edc5f3c3dba0":
        raise ValueError("Cycle source proof changed; repeat the instruction/configuration review")
    dispatch = proof["dispatch"]
    if (dispatch["type1_only_enters_bolt_hold_va"] != 0x6e6625 or
            dispatch["state7_delay_and_release_flags_va"] != 0x6e672d or
            dispatch["state8_bolt_time_va"] != 0x6e67a9 or
            not dispatch["singlefire0_ordinary_shot_does_not_enter_bolt7_8"]):
        raise ValueError("Unsupported bolt instruction dispatch")
    rows = []
    excluded = []
    for source in sniper["descriptors"]:
        v = source["configuration"]["values"]
        if v["fireLogicType"] != 1:
            excluded.append({"key": source["key"], "assetPath": source["configuration"]["assetPath"],
                             "reason": "Exact native dispatch is not fltSingleFireWithBoltAction"})
            continue
        if (v["reloadType"], v["fireInputAction"], v["reloadInputAction"], v["boltDelay"],
                v["holdBoltUntilFireRelease"], v["holdBoltUntilZoomRelease"]) != (1, 8, 29, 0, True, False):
            raise ValueError("Unreviewed active bolt dispatch")
        if word(v["boltTime"]) not in {word(1.6), word(1.65), word(1.8), word(2.3)}:
            raise ValueError("Unreviewed bolt-time source value")
        rows.append(("Bolt", source, file_digest(proof_path)))
    for source in pump["tube_descriptors"]:
        v = source["configuration"]["values"]
        if (v["fireLogicType"], v["reloadType"], v["fireInputAction"], v["reloadInputAction"],
                v["boltDelay"], v["boltTime"], v["holdBoltUntilFireRelease"],
                v["holdBoltUntilZoomRelease"]) != (1, 0, 8, 29, .5, 0, False, False):
            raise ValueError("Unreviewed pump dispatch")
        rows.append(("Pump", source, pump["instruction_proof_digest"]))
    if len(rows) != 42 or len(excluded) != 11:
        raise ValueError("Exact reviewed cycle inventory changed")
    header = ['#pragma once', '#include "Bc2ReloadConfigDescriptor.h"',
              '#include "Bc2NativeCycleEvidence.h"', '// Generated by tools/bc2_cycle_family_registry.py; static instruction review only.',
              'namespace fvr::bc2 {', 'enum class Bc2NativeCycleFamily : unsigned {Pump,Bolt};',
              'struct Bc2CycleNativeProfile {',
              ' const ReloadConfigDescriptor* config=nullptr;Bc2NativeCycleFamily family{};',
              ' std::string_view descriptorDigest,instructionProofDigest;',
              ' NativeCycleHeldBoundary Held(bool empty)const noexcept {',
              '  if(empty)return {6,5,1,family==Bc2NativeCycleFamily::Bolt?.01f:.1f,1.f,true};',
              '  return family==Bc2NativeCycleFamily::Bolt?NativeCycleHeldBoundary{8,7,1,.1f,config->values.boltTime}:',
              '   NativeCycleHeldBoundary{7,6,8,.1f,config->values.boltDelay};',
              ' }',
              ' NativeCycleConvergenceProfile Convergence(bool empty)const noexcept {',
              '  return {family==Bc2NativeCycleFamily::Bolt,empty,config->values.boltDelay,config->values.boltTime};',
              ' }', '};']
    reviews = []
    seen = set()
    for i, (family, source, instruction) in enumerate(rows):
        c = source["configuration"]
        if c["assetPath"] in seen:
            raise ValueError("Ambiguous cycle selector")
        seen.add(c["assetPath"])
        v = c["values"]
        fields = [str(v[key]) for key in ("fireLogicType", "reloadType", "fireInputAction", "reloadInputAction", "baseCapacity", "numberOfMagazines")]
        fields += [f'std::bit_cast<float>(0x{word(v[key]):08x}u)' for key in ("reloadDelay", "reloadTime", "reloadThreshold", "postReloadTime", "boltDelay", "boltTime")]
        fields += [str(v[key]).lower() for key in ("holdBoltUntilFireRelease", "holdBoltUntilZoomRelease")]
        header += [f'inline constexpr ReloadConfigDescriptor CycleNativeConfig{i}' + '{' +
                   json.dumps(c["assetName"]) + ',' + json.dumps(c["assetPath"]) + ',{' + ','.join(fields) +
                   '},{},ReloadDescriptorAdmission::ReviewedNative};']
        reviews.append({"key": source["key"], "configuration": c, "identity": source["identity"],
                        "descriptor_digest": source["descriptor_digest"], "family": family,
                        "instruction_proof_digest": instruction, "native_cycle_admission": True,
                        "review": "Exact complete scalar/object-chain selector; shared type-1 Step state7/8 or empty6 dispatch only",
                        "positive_boundary": [8, 7, 1] if family == "Bolt" else [7, 6, 8],
                        "positive_maximum": v["boltTime"] if family == "Bolt" else v["boltDelay"],
                        "empty_boundary": [6, 5, 1], "empty_maximum": 1,
                        "actual_game_acceptance": False, "headset_acceptance": False,
                        "physical_geometry_admission": False})
    header.append('inline constexpr std::array<Bc2CycleNativeProfile,42> Bc2CycleNativeProfiles{{')
    for i, ((family, source, instruction), review) in enumerate(zip(rows, reviews)):
        header.append(f' {{&CycleNativeConfig{i},Bc2NativeCycleFamily::{family},"{source["descriptor_digest"]}","{instruction}"}},')
    header += ['}};',
               'inline const Bc2CycleNativeProfile* ResolveNativeCycleProfile(const ReloadObservedConfig& c)noexcept {',
               ' const Bc2CycleNativeProfile* found=nullptr;',
               ' for(const auto& row:Bc2CycleNativeProfiles)if(MatchesReloadDescriptor(c,*row.config)){',
               '  if(found)return nullptr;found=&row;', ' }return found;', '}',
               'inline const Bc2CycleNativeProfile* ResolveBoltActionNativeProfile(const ReloadObservedConfig& c)noexcept {',
               ' const auto* p=ResolveNativeCycleProfile(c);return p&&p->family==Bc2NativeCycleFamily::Bolt?p:nullptr;', '}',
               'inline bool ReadNativeCycleProfile(const ReloadStateMemory& memory,const ReloadObservedConfig& c)noexcept {',
               ' const auto* p=ResolveNativeCycleProfile(c);if(!p||!memory.read)return false;',
               ' const auto& v=p->config->values;',
               ' constexpr std::array<std::uint32_t,12> offsets{0xc,0x10,0x14,0x18,0x20,0x24,0x4c,0x50,0x54,0x8c,0x180,0x184};',
               ' const std::array<std::uint32_t,12> expected{std::bit_cast<std::uint32_t>(v.postReloadTime),',
               '  std::bit_cast<std::uint32_t>(v.reloadThreshold),std::bit_cast<std::uint32_t>(v.reloadDelay),',
               '  std::bit_cast<std::uint32_t>(v.reloadTime),std::uint32_t(v.reloadType),std::uint32_t(v.fireLogicType),',
               '  std::uint32_t(v.fireInputAction),std::bit_cast<std::uint32_t>(v.boltTime),',
               '  std::bit_cast<std::uint32_t>(v.boltDelay),std::uint32_t(v.reloadInputAction),',
               '  std::uint32_t(v.numberOfMagazines),std::uint32_t(v.baseCapacity)};',
               ' std::array<std::uint32_t,12> a{},b{};',
               ' if(std::uint64_t(c.primaryFire)+0x188>UINT32_MAX)return false;',
               ' for(unsigned pass=0;pass<2;++pass)for(unsigned n=0;n<offsets.size();++n)',
               '  if(!memory.read(memory.context,c.primaryFire+offsets[n],&(pass?b:a)[n],4))return false;',
               ' std::array<unsigned char,2> flags{},again{};',
               ' return a==expected&&b==a&&memory.read(memory.context,c.primaryFire+0x58,flags.data(),2)&&',
               '  memory.read(memory.context,c.primaryFire+0x58,again.data(),2)&&flags==again&&',
               '  flags[0]==unsigned(v.holdBoltUntilZoomRelease)&&flags[1]==unsigned(v.holdBoltUntilFireRelease);',
               '}', '} // namespace fvr::bc2', '']
    manifest = {"schema": "fvr.bc2.exact_cycle_static_review.v1", "evidence_level": "static native instruction/configuration review",
                "source_files": [{"path": str(p.relative_to(root)).replace("\\", "/"), "sha256": file_digest(p)}
                                 for p in (sniper_path, proof_path, pump_path)],
                "reviewer": "cycle45 native-cycle service source review", "reviews": reviews, "excluded": excluded,
                "limits": "No per-gun live or headset result; physical geometry and loaded-asset proof remain separate gates."}
    return "\n".join(header), json.dumps(manifest, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    header, manifest = generate(args.root)
    for relative, text in (("src/games/bc2/Bc2BoltActionNativeProfile.h", header),
                           ("profiles/weapons45-cycles/exact-cycle-reviews.json", manifest)):
        path = args.root / relative
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                raise SystemExit(f"Generated cycle source differs: {relative}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    print("42 exact cycle profiles (17 bolt, 25 pump); 11 non-bolt sniper configurations excluded")


if __name__ == "__main__":
    main()
