"""Derived offline raw-contact fixture from the existing exact normal bindings.

Run after StorageBudget admission. No extraction of game bytes to disk, no
enrollment changes, no native/headset acceptance. Only named transforms and
their source hashes are retained; selected authored controls are evaluated by
the existing decoder, not replaced with magazine-profile geometry.
"""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'tools'))
from bc2_magazine_contact_batch import ArchivePool
from bc2_authored_magazine_geometry import exact_resource
from bc2_weapon_animation_pipeline import Skeleton, Clip, canonical

GAME = Path('G:/New folder (2)/Battlefield Bad Company 2')
SOURCE = ROOT / 'reports/coordinator-20261030-magazines45-policy04/bindings.json'
OUT = ROOT / 'tests/Bc2MagazineRawContactPipelineFixture.generated.h'
REPORT = ROOT / 'reports/coordinator-20261030-offline57/magazine-raw-pipeline/fixture.json'


def number(value):
    text = format(value, '.9g')
    return text + ('f' if '.' in text or 'e' in text else '.f')


def matrix(values):
    return 'math::Matrix4{{{' + ','.join('{{' + ','.join(number(v) for v in values[n:n+4]) + '}}' for n in range(0, 16, 4)) + '}}}'


def run():
    source_bytes = SOURCE.read_bytes()
    profiles = json.loads(source_bytes)['profiles']
    common = next(p['skeleton_source'] for p in profiles if p['skeleton_source']['archive'].casefold() == 'dist/win32/levels/mp_common/level-00.fbrb')
    pool = ArchivePool(GAME, common['archive'], common['archive_index_sha256'])
    skeletons, poses, cases, receipts = {}, {}, [], []
    for profile in profiles:
        chain = profile['animation_chain']
        for role, resource, kind, expected in (
            ('skeleton', chain['skeleton_resource'], 'GrannyModel', profile['skeleton_sha256']),
            ('animation', chain['animation_resource'], 'GrannyAnimation', profile['animation_sha256'])):
            source = profile[role + '_source']
            archive = pool(GAME / source['archive'])
            assert archive.index_sha256 == source['archive_index_sha256']
            cache = skeletons if role == 'skeleton' else poses
            if expected not in cache:
                data = exact_resource(archive, resource, kind, expected)
                cache[expected] = Skeleton(data) if role == 'skeleton' else Clip(data)
        skeleton, clip = skeletons[profile['skeleton_sha256']], poses[profile['animation_sha256']]
        assert skeleton.fingerprint == profile['rig_fingerprint']
        weapon = skeleton.names.index(profile['weapon_bone'])
        def weapon_member(index):
            while index >= 0:
                if index == weapon:return True
                index = skeleton.parents[index]
            return False
        # Membership follows exact topology, including authored names such as
        # jntWpnwpnJnt_16/14. A spelling prefix would silently leave those
        # magazine roots/intermediaries at bind pose while moving their children.
        names = [name for index, name in enumerate(skeleton.names) if weapon_member(index) or name.startswith('LeftHand') or name == 'RightHand']
        # Only selected named controls and their exact ancestors are evaluated.
        # Other bones retain the authored bind pose in this read-only fixture.
        frames = []
        for time in (0., clip.duration / 2, clip.duration):
            result = clip.evaluate(skeleton, time, names)
            frames.append([(skeleton.names.index(name), result['weapon_relative'][name]) for name in names])
        cases.append((profile, frames))
        receipts.append(dict(asset=profile['native_asset_name'], configuration=profile['weapon']['resource'][:-4],
                             mesh=profile['configured_mesh_path'], binding=profile['binding_digest'],
                             skeleton=profile['skeleton_sha256'], clip=profile['animation_sha256'],
                             sample_seconds=[0., clip.duration / 2, clip.duration]))
    lines = ['// Derived named transforms only; generated by offline57/magazine-raw-pipeline/generate_fixture.py.',
             '// Actual source hashes are retained in fixture.json. No runtime or headset acceptance.',
             '#pragma once', '#include "Bc2Rig.h"', '#include "fvr/interaction/ReloadInsertion.h"',
             'namespace magazine_raw_fixture {', 'using namespace fvr;using namespace fvr::bc2;',
             'struct PoseCase {std::string_view asset,configuration,mesh;unsigned skeleton,pose;};']
    skeys = list(skeletons)
    for i, key in enumerate(skeys):
        skeleton = skeletons[key]
        lines += [f'// Skeleton SHA256 {key}', f'inline RigSnapshot Skeleton{i}() {{RigSnapshot r;']
        lines += ['r.names={' + ','.join(json.dumps(n) for n in skeleton.names) + '};',
                  'r.parents={' + ','.join(map(str, skeleton.parents)) + '};', 'r.inverseBind={']
        for bone in skeleton.bones:
            native = list(bone['InverseWorldTransform'])
            for row in range(4):native[row*4+3] = float(row == 3)
            lines.append(matrix(canonical(native)) + ',')
        lines += ['};r.weaponBone=' + str(skeleton.names.index('jntWpn_1')) + ';',
                  'for(const auto& inverse:r.inverseBind)r.evaluatedWorld.push_back(*interaction::InverseAnimatedTransform(inverse));',
                  'return r;}']
    unique = {}
    indices = []
    for profile, frames in cases:
        key = (profile['skeleton_sha256'], profile['animation_sha256'])
        if key not in unique:
            index = len(unique);unique[key] = index
            lines += [f'// Selected clip SHA256 {key[1]}', f'inline const std::array<std::vector<interaction::BoneWrite>,3> Pose{index}{{{{']
            for frame in frames:
                lines += ['{'] + ['{' + str(bone) + ',' + matrix(transform) + '},' for bone, transform in frame] + ['},']
            lines += ['}};']
        indices.append(unique[key])
    lines += [f'inline const std::array<PoseCase,{len(cases)}> Cases{{{{']
    for (profile, frames), pose in zip(cases, indices):
        lines += ['{' + ','.join(json.dumps(profile[k]) for k in ('native_asset_name',)) + ',' +
                  json.dumps(profile['weapon']['resource'][:-4]) + ',' + json.dumps(profile['configured_mesh_path']) + ',' +
                  str(skeys.index(profile['skeleton_sha256'])) + ',' + str(pose) + '},']
    lines += ['}};', 'inline RigSnapshot Rig(const PoseCase& c,unsigned sample){RigSnapshot r;', 'switch(c.skeleton){']
    lines += [f'case {n}:r=Skeleton{n}();break;' for n in range(len(skeys))]
    lines += ['default:return {};}', 'const std::vector<interaction::BoneWrite>* writes=nullptr;switch(c.pose){']
    lines += [f'case {n}:writes=&Pose{n}[sample];break;' for n in range(len(unique))]
    lines += ['default:return {};}', 'for(const auto& w:*writes)r.evaluatedWorld[w.index]=w.transform;', 'return r;}', '}']
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    report = dict(schema='fvr.bc2.offline57.raw_contact_fixture.v1', source=str(SOURCE),
                  source_sha256=hashlib.sha256(source_bytes).hexdigest(), cases=receipts,
                  skeletons=len(skeys), selected_clips=len(unique),
                  output=str(OUT), output_sha256=hashlib.sha256(OUT.read_bytes()).hexdigest(),
                  no_native_or_headset_acceptance=True)
    REPORT.write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(dict(cases=len(cases), skeletons=len(skeys), clips=len(unique), bytes=OUT.stat().st_size)))


if __name__ == '__main__':
    run()
